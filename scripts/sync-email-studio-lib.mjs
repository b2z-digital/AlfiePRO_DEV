// Copies the shared Email studio renderer (src/lib/emailStudio) and the results scoring
// into the email-studio edge function, so the app and the sender render emails the same way.
// Run after changing any of those files:  node scripts/sync-email-studio-lib.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'supabase/functions/email-studio/lib');
mkdirSync(join(out, 'scoring'), { recursive: true });
const banner = '// GENERATED by scripts/sync-email-studio-lib.mjs. Edit the source in src/ and re-run.\n';

for (const f of readdirSync(join(root, 'src/lib/emailStudio')).filter(f => f.endsWith('.ts'))) {
  writeFileSync(join(out, f), banner + readFileSync(join(root, 'src/lib/emailStudio', f), 'utf8'));
}

const read = p => readFileSync(join(root, p), 'utf8');
const loose = '// @ts-nocheck: copied app code, type-checked in the app\n';
let standings = read('src/utils/standingsCalculator.ts')
  .replace("import { RaceEvent } from '../types/race';", '// deno-lint-ignore no-explicit-any\ntype RaceEvent = any;')
  .replace("import { LetterScore } from '../types';", 'type LetterScore = string;')
  .replace("import { getLetterScorePointsForRace } from './scratchCalculations';", "import { getLetterScorePointsForRace } from './scratchCalculations.ts';")
  .replace("import { combineAllDayResults } from './raceStorage';", "import { combineAllDayResults } from './combineDays.ts';");
if (/from '\.\.?\/[^']*(?<!\.ts)'/.test(standings)) throw new Error('standingsCalculator has an import the sync script does not know about');
writeFileSync(join(out, 'scoring/standingsCalculator.ts'), banner + loose + standings);

let scratch = read('src/utils/scratchCalculations.ts').replace("from '../types/letterScores';", "from './letterScores.ts';");
if (/from '\.\.?\/[^']*(?<!\.ts)'/.test(scratch)) throw new Error('scratchCalculations has an import the sync script does not know about');
writeFileSync(join(out, 'scoring/scratchCalculations.ts'), banner + loose + scratch);
writeFileSync(join(out, 'scoring/letterScores.ts'), banner + read('src/types/letterScores.ts'));

// combineAllDayResults lives in raceStorage.ts (which pulls in the app's Supabase client), so copy just that function
const rs = read('src/utils/raceStorage.ts');
const start = rs.indexOf('export const combineAllDayResults');
const end = rs.indexOf('\n};\n', start) + 4;
if (start < 0 || end < 4) throw new Error('combineAllDayResults not found in raceStorage.ts');
writeFileSync(join(out, 'scoring/combineDays.ts'), banner + loose + '// deno-lint-ignore no-explicit-any\ntype RaceEvent = any;\n' + rs.slice(start, end));
console.log('Email studio lib synced to', out);
