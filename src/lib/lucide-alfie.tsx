/**
 * Drop-in replacement for 'lucide-react' (wired up in vite.config.ts).
 * Re-exports the whole library, and swaps the icons below for their Alfie
 * glyphs when rendered inside the signed-in app (AlfieIconContext = true).
 * Outside the app (public club / event websites) every icon is untouched.
 */
import React, { forwardRef, useContext } from 'react';
import * as L from 'lucide-react-original';
import { AlfieIcon, AlfieIconContext } from '../components/brand/AlfieIcon';

export * from 'lucide-react-original';

type IconComponent = React.ForwardRefExoticComponent<any>;

function themed(Original: IconComponent, glyph: string, name: string): IconComponent {
  const C = forwardRef<SVGSVGElement, any>((props, ref) => {
    const on = useContext(AlfieIconContext);
    return on
      ? React.createElement(AlfieIcon, { ...props, glyph, ref })
      : React.createElement(Original, { ...props, ref });
  });
  C.displayName = name;
  return C;
}

